-- فلتر النتايج — أنشر الكل، ولا الفوز بس، ولا الخسارة بس
--
-- `telegram.outcomes` في `configs`: all | wins | losses. غيابه معناه **all** —
-- السلوك اللي شغال دلوقتي، وحقل ناقص مايغيّرش حاجة شغالة.
--
--   all     كل نتيجة بتتنشر زي ما التسوية قالتها: ربح، خسارة، تعادل، وبدون
--           سعر عند الانتهاء.
--   wins    رسالة النتيجة بتتبعت لو الصفقة **كسبت** بس.
--   losses  لو **خسرت** بس.
--
-- التعادل و«بدون سعر» مش فوز ولا خسارة، فمابيتنشروش غير في `all`. حطّهم مع
-- الفوز كان هيخلي «الفوز بس» تعني حاجة تانية غير اسمها.
--
-- ── ده الفلتر الوحيد اللي بيبص للنتيجة، وده مهم ────────────────────────────
--
-- كل الحدود اللي قبله بتتقرر **قبل** ما النتيجة توجد: حد العمق وقت الفتح،
-- ونوع الرسايل (`publish`) على مستوى الفئة، وصف الأهلية `elig` وقت الفتح.
-- ده كان مقصود: كل إشارة اتنشرت فضلت تنبؤ حقيقي بيكسب أو يخسر قدام الناس.
--
-- `outcomes` بيكسر الخط ده عن قصد. مع `wins` القناة بتفضل تنشر الإشارة وهي
-- مفتوحة (نتيجتها لسه مش موجودة، فالتنبؤ حقيقي)، لكن سجل النتايج اللي فاضل
-- على القناة بيبقى مش سجل — الخسارة موجودة، بس مش مكتوبة. اللوحة في الأدمن
-- بتقول ده بالنص لما تختار غير `all`، لأن ده قرار عن اللي الناس هتصدّقه، مش
-- إعداد شكلي.
--
-- ملخص آخر اليوم **مابيتأثرش**: أرقامه من كل صفقات اليوم، فاضلة صحيحة. يعني
-- في وضع `wins` الملخص هو الحتة الوحيدة اللي بتقول النسبة الحقيقية — سيبه
-- شغال ولا اقفله من سويتش `daily`، بس اعرف إنك بتختار بين رسايل بتقول حاجة
-- وملخص بيقول غيرها.
--
-- ── العقد مع المولّد ───────────────────────────────────────────────────────
--
-- عند رسالة النتيجة، بعد ما `elig` و`publish` يعدّوا وقبل أي إرسال أو إدخال
-- في `telegram_queue`: لو `outcomes` مش `all` وناتج التسوية مش مطابق — سيبها،
-- بلاش تبعت وبلاش تحطها في الطابور. رسالة الفتح مالهاش دعوة بالفلتر ده:
-- ساعتها النتيجة لسه مش موجودة، ومحدش يقدر يفلتر على حاجة مش موجودة.
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

-- الصف موجود من ترحيل `telegram_alerts`؛ ده بيضيف المفتاح الناقص من غير ما
-- يلمس أي قيمة تانية. الافتراضي `all` — الترحيل مايقللش اللي بيتنشر.
UPDATE public.configs
   SET data = jsonb_set(data, '{outcomes}', '"all"')
 WHERE id = 'telegram' AND NOT (data ? 'outcomes');

COMMIT;
