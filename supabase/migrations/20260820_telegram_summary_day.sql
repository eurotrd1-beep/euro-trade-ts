-- ════════════════════════════════════════════════════════════════════════════
-- الملخص يتبعت آخر يومك إنت، مش آخر يوم Greenwich
--
-- الملخص كان مربوط باليوم بتوقيت UTC. لواحد في القاهرة (UTC+3) ده معناه إن
-- ملخص يومه بيوصل الساعة ٣ الفجر بعد ما صفقات اليوم اللي بعده تكون بدأت خلاص
-- — مش عطل، اليوم نفسه كان معرّف بتوقيت تاني.
--
-- `telegram.summaryOffsetMinutes`: دقايق تتزاد على UTC عشان توصل «يومك».
-- القاهرة = 180. غيابه معناه صفر — يعني UTC، السلوك القديم بالظبط.
--
-- ── ده بيحرّك الملخص لوحده ─────────────────────────────────────────────────
--
-- كل حاجة تانية في النظام بتتجمّع على يوم UTC: `signal_daily`، والـrollup،
-- والتنظيف، ومدى التواريخ في صفحة إحصائيات الإشارات. ولا واحدة فيهم اتحركت،
-- عشان تحريكهم كان هيغيّر أرقام تاريخية موجودة من قبل.
--
-- يعني في وضع +3، نافذة الملخص (٢١:٠٠ UTC امبارح ← ٢٠:٥٩ UTC النهاردة) مش
-- نفس نافذة «أمس» في صفحة الإحصائيات (٠٠:٠٠ ← ٢٣:٥٩ UTC). الأرقام هتفرق،
-- والفرق ده مقصود ومعلن: رسالة الملخص نفسها بتكتب المنطقة الزمنية في عنوانها
-- («📊 ملخص 2026-08-19 (بتوقيت UTC+3)») لما تكون مش UTC، عشان أول واحد يقارن
-- الرقمين مايستنتجش إن واحد فيهم بايظ.
--
-- ── ليه الافتراضي هنا 180 مش 0 ─────────────────────────────────────────────
--
-- الترحيل ده بيتطبّق على قاعدة واحدة معروفة: القناة عربية والمشغّل في القاهرة،
-- و«آخر اليوم» عنده هو نص الليل بتوقيته. المولّد نفسه لسه افتراضيه صفر (UTC)
-- لو الحقل مش موجود — يعني أي تشغيل تاني ماشغّلش الترحيل ده مابيتغيرش عنده
-- حاجة. الرقم ظاهر ومتغيّر من الأدمن في أي وقت.
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

UPDATE public.configs
   SET data = jsonb_set(data, '{summaryOffsetMinutes}', '180')
 WHERE id = 'telegram' AND NOT (data ? 'summaryOffsetMinutes');

COMMIT;
