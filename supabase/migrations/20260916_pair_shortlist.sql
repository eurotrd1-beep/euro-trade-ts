-- قائمة مختصرة — 25 زوج بدل 89
--
-- الاختيار اتعمل على السيولة والشهرة العالمية للزوج نفسه، مش على أي إحصائية
-- من بياناتنا. السبب إن اللي متخزّن نافذة 100 شمعة متدحرجة لكل سلسلة، وده
-- مبيسمحش بترتيب أزواج؛ لو اتّرتبوا بيه هيبقى انتقاء منحاز على عيّنة صغيرة.
--
-- البيانات اتستخدمت في حاجة واحدة بس: **استبعاد الميت**. والقياس اللي خلّى ده
-- ممكن هو إن السكرابر بيكتب شمعة جديدة لما السعر يتغيّر بس:
--
--     if (price !== last.c) { arr.push(...) }     // po-scraper.js _tickIv
--
-- يعني عدد الإغلاقات المختلفة في الـ100 شمعة قياس مباشر لحياة الرمز. واللي
-- اتشال بيه:
--
--   XAGUSD  الفضة العادية — 100 شمعة، **إغلاق واحد مختلف**، مدى 0.0 نقطة أساس
--   XAUUSD  الدهب العادي  — آخر شمعة متأخرة ~28 يوم، 21 إغلاق على 32 يوم
--
-- الاتنين اتبدلوا بنسختهم OTC، وهي محدّثة وبتتحرك فعلاً.
--
-- ── ليه مفيش NZD/USD حقيقي ─────────────────────────────────────────────────
--
-- `isAllowedAsset('NZDUSD')` بترجّع true خلاص — الفلتر بتاعنا مش هو المانع.
-- و`otc_pairs` بيتملي من مسح أصول Pocket Option نفسها (`_upsertLibrary`).
-- الرمز مش موجود، ومعاه في الكتالوج أربع أزواج NZD تانية كلهم OTC. يعني
-- المنصة مش بتقدّم NZD/USD كسوق حقيقي. المتاح هو `NZDUSD_otc` وهو اللي اتاخد.
--
-- ── الميكانيكا: إيه اللي بيتشال وإيه اللي بيتقفل ───────────────────────────
--
-- `candles` بيتشال — ده مكان المساحة والباندويدث الحقيقي (2,454 ك.بايت →
-- 540، ومسحة الـ1m على السلك من 111.6 ك.بايت لـ24.1).
--
-- `otc_pairs` **مبيتشالش، بيتقفل**. ده الجدول اللي السكرابر بيقرا منه
-- (`loadEnabledSymbols` بتاخد enabled = true بس)، وهو كمان الكتالوج اللي
-- الأدمن بيتصفحه. حذف الصف مش هيثبت أصلاً: أول مسح أصول هيرجّعه تاني، لأن
-- `_upsertLibrary` بيعمل upsert لكل اللي المنصة بتعلنه. لكن التعليق ثابت —
-- `enabled` مش في حمولة الـupsert عن قصد، فهو بيفضل زي ما هو عبر أي مسح.
-- وعشان رمز **جديد** تمامًا تعلنه المنصة بكرة ميجيش مفتوح، الافتراضي بيتغيّر
-- لـfalse تحت.
--
-- `pairs` بيتشال — دي القايمة اللي المستخدم بيشوفها، والتطبيق بيسحبها كاملة
-- (`select('*')`) وبيفلتر enabled في المتصفح، فالصف المتعطّل بيفضل بيتنقل على
-- الشبكة. وهي مبتتبنيش من المسح، فالحذف بيثبت. التراجع ممكن: الكتالوج كله لسه
-- في `otc_pairs`.
-- ════════════════════════════════════════════════════════════════════════════

BEGIN;

-- ── العشرين ────────────────────────────────────────────────────────────────
--
-- ستة رئيسية في السوق الحقيقي: أكبر ست أزواج دولار في العالم (~60% من حجم
-- الفوركس كله). وأربع كروسات من أشهر ما يتداول. وستة OTC نسخ الرئيسية، مع
-- كروسين OTC، والدهب والفضة — والعشرة OTC دول بيشتغلوا سبت وحد كمان.
--
-- اللي اتخطّى بفلتر البيانات، وكل واحد اتاخد بدله اللي بعده في الترتيب:
--
--   EURGBP      ثاني أكبر كروس عالميًا — وقف 2,634 دقيقة (~44 س) قبل الباقي
--   AUDUSD_otc  وقف 2,717 دقيقة                  → USDCHF_otc بدله
--   EURJPY_otc  وقف 2,731 دقيقة                  → GBPJPY_otc بدله
--   EURCAD · GBPCAD  نفس النمط، ومدخلوش الترتيب أصلاً
--
-- ملحوظة على EUR/GBP: النسخة العادية واقفة لكن `EURGBP_otc` حية تمامًا
-- (92 إغلاق مختلف، مدى 81.6 نقطة أساس) — فالزوج داخل في شكله الـOTC.
CREATE OR REPLACE FUNCTION public.pair_kept(sym text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT sym IN (
    -- رئيسية، سوق حقيقي
    'EURUSD',
    'USDJPY',
    'GBPUSD',
    'USDCHF',
    'USDCAD',
    'AUDUSD',
    -- كروسات معروفة، سوق حقيقي
    'EURJPY',
    'GBPJPY',
    'EURCHF',
    'AUDJPY',
    'CHFJPY',
    'CADJPY',
    -- OTC — بتشتغل السبت والحد كمان
    'EURUSD_otc',
    'USDJPY_otc',
    'GBPUSD_otc',
    'USDCHF_otc',
    'USDCAD_otc',
    'AUDUSD_otc',
    'NZDUSD_otc',
    'EURJPY_otc',
    'GBPJPY_otc',
    'EURCHF_otc',
    'AUDJPY_otc',
    'CHFJPY_otc',
    -- الذهب — OTC بس، الحقيقي ميت
    'XAUUSD_otc'
  );
  -- ── متشالين مؤقتًا، لحد ما نتأكد ─────────────────────────────────────────
  --
  -- أول جلسة ديمو شغالة قارنّا أسعارها بالمخزّن. سبعتاشر زوج طلعوا في حدود
  -- 0.3–2.5% — ده أحد عشر يوم سوق، منطقي. اتنين مطلعوش:
  --
  --   XAGUSD_otc   ديمو 68.22 مقابل 19.25 مخزّن  (+254%)
  --   EURGBP_otc   ديمو 0.927 مقابل 0.837 مخزّن  (+10.8%)
  --
  -- 68 مش سعر فضة أصلًا. وأدوات OTC **تركيبية** من المنصة، فمولّد الديمو
  -- ممكن يكون غير مولّد الحساب — واستراتيجية بتتقاس على سلسلة وبتتداول على
  -- غيرها بتبقى بلا معنى. فالاتنين بره لحد ما الفرق يتفسّر.
  --
  -- الثمن: الفضة بتختفي تمامًا (XAGUSD العادي مجمّد)، و EUR/GBP كمان
  -- (نسخته العادية واقفة من ~44 ساعة). ترجّعهم بإضافة السطرين هنا.
$$;

COMMENT ON FUNCTION public.pair_kept(text) IS
  'العشرين زوج المختارين على السيولة العالمية. البيانات اتستخدمت للاستبعاد بس.';

-- ── الشموع: ده اللي بياخد المساحة ──────────────────────────────────────────
--
-- بيتشال الأول عشان لو حاجة وقعت بعد كده، الجداول الصغيرة تفضل مقروءة.
DELETE FROM public.candles
 WHERE key !~ '_(1m|5m|15m|30m|1h|1D)$'
    OR NOT public.pair_kept(regexp_replace(key, '_(1m|5m|15m|30m|1h|1D)$', ''));

-- ── مكتبة الرموز: تعطيل مش حذف ─────────────────────────────────────────────
UPDATE public.otc_pairs
   SET enabled = false, updated_at = now()
 WHERE enabled = true
   AND NOT public.pair_kept(symbol);

-- والعشرين مفتوحين صراحةً، عشان الترحيل يوصف الحالة النهائية كلها مش نصّها.
UPDATE public.otc_pairs
   SET enabled = true, updated_at = now()
 WHERE public.pair_kept(symbol)
   AND enabled IS DISTINCT FROM true;

-- رمز جديد تعلنه المنصة بعد كده يدخل مقفول ويستنى قرار، بدل ما يبدأ يتخزّن
-- من نفسه. القرار ده هو الفرق بين قايمة مختارة وقايمة بتكبر لوحدها.
ALTER TABLE public.otc_pairs ALTER COLUMN enabled SET DEFAULT false;

-- ── القايمة اللي التطبيق بيعرضها ───────────────────────────────────────────
DELETE FROM public.pairs
 WHERE NOT public.pair_kept(chart_symbol);

-- ── لقطة الأسعار ───────────────────────────────────────────────────────────
--
-- السكرابر بيعيد كتابتها كل 20 ثانية من الرموز المفعّلة فهي بتتنضّف لوحدها،
-- بس التنضيف هنا معناه إن أول تشغيل بارد بعد الترحيل ميقراش أسعار أزواج
-- مابقتش في القايمة.
UPDATE public.price_snapshot
   SET data = (
     SELECT COALESCE(jsonb_object_agg(k, v), '{}'::jsonb)
       FROM jsonb_each(data) AS e(k, v)
      WHERE public.pair_kept(k)
   )
 WHERE id = 'otc_prices'
   AND jsonb_typeof(data) = 'object';

COMMIT;

